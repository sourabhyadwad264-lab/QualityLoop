import { useEffect, useState } from "react";
import { api } from "../api.js";

// Read-only report page. Opens without login. Print it, or choose "Save as PDF" in the print window.
export default function PublicReport({ token }) {
  const [r, setR] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => { api.publicReport(token).then(setR).catch((e) => setError(e.message)); }, [token]);

  if (error) return <div className="sheet"><div className="alert alert-danger m-0">{error}</div></div>;
  if (!r) return <div className="sheet">Loading report...</div>;

  const row = (label, value) => <tr><th>{label}</th><td>{value || "-"}</td></tr>;

  return (
    <div className="sheet">
      <div className="d-flex justify-content-between align-items-start mb-3">
        <div>
          <div className="text-secondary">Defect report</div>
          <h1 className="h3 m-0">#{r.id} {r.title}</h1>
        </div>
        <button className="btn btn-success no-print" onClick={() => window.print()}>Print / Save as PDF</button>
      </div>

      <table className="table table-sm">
        <tbody>
          {row("Part number", r.partNumber)}
          {row("Part name", r.partName)}
          {row("Found through", r.source && r.source.replaceAll("_", " ").toLowerCase())}
          {row("Quantity affected", r.quantityAffected)}
          {row("Detected on", r.detectedOn)}
          {row("Detected by", r.detectedBy)}
          {row("Severity", r.severity)}
          {row("Status", r.status.replace("_", " "))}
          {row("Problem", r.description)}
          {row("Containment action", r.containmentAction)}
          {row("Root cause", r.rootCause)}
        </tbody>
      </table>

      <h2 className="h6 mt-4">Corrective actions</h2>
      {r.actions.length === 0 ? (
        <p className="text-secondary">No corrective actions recorded yet.</p>
      ) : (
        <table className="table table-sm table-bordered">
          <thead><tr><th>Action</th><th>Owner</th><th>Due</th><th>Status</th></tr></thead>
          <tbody>
            {r.actions.map((a, i) => (
              <tr key={i}><td>{a.description}</td><td>{a.owner}</td><td>{a.dueDate}</td><td>{a.status}</td></tr>
            ))}
          </tbody>
        </table>
      )}
      <p className="text-secondary mt-4 mb-0"><small>Generated by QualityLoop. Closed on: {r.closedAt ? r.closedAt.slice(0, 10) : "not closed yet"}</small></p>
    </div>
  );
}
